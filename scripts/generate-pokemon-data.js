// scripts/generate-pokemon-data.js
// One-time generator: pulls base stats for IDs 1-386 from the PokéAPI and
// rewrites PokemonData.txt on the app's stat scale (level 100, 31 IV /
// 252 EV, neutral nature): HP = 2*base + 204, all other stats = 2*base + 99.
//
// It also emits src/spriteIds.generated.js mapping each name to its dex id,
// so the app never needs network lookups at startup.
//
// Usage: node scripts/generate-pokemon-data.js
// The script FAILS (non-zero exit) if the four original Pokémon's rows
// would change, which protects the hand-verified balance of the original data.
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const ROOT = path.join(__dirname, "..");
const DATA_PATH = path.join(ROOT, "PokemonData.txt");
const SPRITE_PATH = path.join(ROOT, "src", "spriteIds.generated.js");
const FIRST_ID = 1;
const LAST_ID = 386; // end of Generation 3
const CONCURRENCY = 12;
const TIMEOUT_MS = 20000;

const STAT_COLUMNS = ["HP", "Attack", "Defense", "SpecialAttack", "SpecialDefense", "Speed"];

// "mr-mime" -> "Mr-Mime", "bulbasaur" -> "Bulbasaur" (single token, safe for the whitespace parser)
const prettyName = (apiName) =>
  apiName
    .split("-")
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join("-");

const scaleStat = (base, key) => (key === "HP" ? 2 * base + 204 : 2 * base + 99);

async function fetchPokemon(id) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const res = await fetch(`https://pokeapi.co/api/v2/pokemon/${id}`, {
      signal: controller.signal,
    });
    if (!res.ok) throw new Error(`HTTP ${res.status} for /pokemon/${id}`);
    return res.json();
  } finally {
    clearTimeout(timer);
  }
}

async function runInBatches(ids) {
  const results = [];
  for (let i = 0; i < ids.length; i += CONCURRENCY) {
    const batch = ids.slice(i, i + CONCURRENCY);
    const data = await Promise.all(batch.map(fetchPokemon));
    results.push(...data);
    process.stdout.write(`  fetched ${results.length}/${ids.length}\r`);
  }
  process.stdout.write("\n");
  return results;
}

async function main() {
  const ids = [];
  for (let id = FIRST_ID; id <= LAST_ID; id++) ids.push(id);

  console.log(`Fetching ${ids.length} Pokemon from pokeapi.co...`);
  const raw = await runInBatches(ids);

  const entries = raw.map((p) => {
    const baseByKey = {};
    for (const st of p.stats) baseByKey[st.stat.name] = st.base_stat; // hp, attack, defense, special-attack, ...
    const base = {
      HP: baseByKey["hp"],
      Attack: baseByKey["attack"],
      Defense: baseByKey["defense"],
      SpecialAttack: baseByKey["special-attack"],
      SpecialDefense: baseByKey["special-defense"],
      Speed: baseByKey["speed"],
    };
    const scaled = {};
    for (const col of STAT_COLUMNS) scaled[col] = scaleStat(base[col], col);
    return { id: p.id, name: prettyName(p.name), stats: scaled };
  }).sort((a, b) => a.id - b.id);

  // Sanity check: the original four Pokémon must not change.
  const expected = {
    Pikachu:   { HP: 274, Attack: 209, Defense: 179, SpecialAttack: 199, SpecialDefense: 199, Speed: 279 },
    Charizard: { HP: 360, Attack: 267, Defense: 255, SpecialAttack: 317, SpecialDefense: 269, Speed: 299 },
    Blastoise: { HP: 362, Attack: 265, Defense: 299, SpecialAttack: 269, SpecialDefense: 309, Speed: 255 },
    Venusaur:  { HP: 364, Attack: 263, Defense: 265, SpecialAttack: 299, SpecialDefense: 299, Speed: 259 },
  };
  for (const [name, stats] of Object.entries(expected)) {
    const found = entries.find((e) => e.name === name);
    if (!found) { console.error(`FATAL: ${name} missing from roster`); process.exit(1); }
    for (const col of STAT_COLUMNS) {
      if (found.stats[col] !== stats[col]) {
        console.error(`FATAL: ${name} ${col} changed: expected ${stats[col]}, got ${found.stats[col]}`);
        process.exit(1);
      }
    }
  }
  console.log("Original four Pokémon verified unchanged.");

  const header = "Name " + STAT_COLUMNS.join(" ");
  const lines = entries.map(
    (e) => `${e.name} ${STAT_COLUMNS.map((col) => e.stats[col]).join(" ")}`
  );
  fs.writeFileSync(DATA_PATH, [header, ...lines].join("\n") + "\n");
  console.log(`Wrote ${lines.length} rows to PokemonData.txt`);

  // Sprite map: plain script + UMD export for the Node tests.
  const spriteMap = Object.fromEntries(entries.map((e) => [e.name, e.id]));
  const generated =
    "// Generated by scripts/generate-pokemon-data.js. Do not edit by hand.\n" +
    "const SPRITE_IDS = " + JSON.stringify(spriteMap, null, 0) + ";\n\n" +
    'if (typeof module !== "undefined" && module.exports) {\n' +
    "  module.exports = { SPRITE_IDS };\n" +
    "}\n";
  fs.writeFileSync(SPRITE_PATH, generated);
  console.log(`Wrote sprite IDs for ${entries.length} Pokémon to src/spriteIds.generated.js`);
}

main().catch((err) => {
  console.error("Generation failed:", err);
  process.exit(1);
});
